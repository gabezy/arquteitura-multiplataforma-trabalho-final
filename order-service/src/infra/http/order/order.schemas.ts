import { z } from 'zod';
import { Marketplace } from '../../../core/order/model/marketplace.vo';
import { OrderStatus } from '../../../core/order/model/order-status.vo';
import { MAX_PAGE_SIZE } from '../../../core/order/port/in/query-orders.port';

const oneOf = (values: readonly { value: string }[]) => values.map(({ value }) => value) as [string, ...string[]];

// Digits only: "", "1.5", "-1" and "1e3" are rejected instead of being read as numbers.
const wholeNumber = z.string().regex(/^\d+$/, 'must be a whole number').transform(Number);

// Checks the shape of the request; the facade checks the same bounds again for any other caller.
export const listOrdersQuerySchema = z.object({
  marketplace: z.enum(oneOf(Marketplace.ALL), `must be one of ${Marketplace.ALL.map(m => m.value).join(', ')}`).optional(),
  status: z.enum(oneOf(OrderStatus.ALL), `must be one of ${OrderStatus.ALL.map(s => s.value).join(', ')}`).optional(),
  limit: wholeNumber.pipe(z.number().min(1, 'must be at least 1').max(MAX_PAGE_SIZE, `must be at most ${MAX_PAGE_SIZE}`)).optional(),
  offset: wholeNumber.pipe(z.number().max(Number.MAX_SAFE_INTEGER, 'is too large')).optional(),
});

// Any UUID: the ids are generated by this service, but a lookup by another shape must answer 400, not 404.
export const orderIdParamsSchema = z.object({
  id: z.guid('must be a UUID'),
});
